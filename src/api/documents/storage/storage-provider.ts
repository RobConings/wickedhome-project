import type { Readable } from "node:stream";

/** Matches the Prisma enum `DocumentStorageProvider`. */
export type StorageProviderName = "LOCAL" | "GOOGLE_DRIVE";

/** What `put` stored: the key to find it again, plus what was measured while streaming. */
export type StoredObject = {
  key: string;
  sizeBytes: number;
  /** Hex SHA-256 of the content. */
  sha256: string;
};

export type PutOptions = {
  /** The household the object belongs to; providers use it to partition storage. */
  householdId: string;
  /** Abort with `StorageLimitError` as soon as more than this many bytes arrive. */
  maxBytes: number;
};

/** Inclusive byte range, like an HTTP `Range: bytes=start-end`. */
export type ByteRange = { start: number; end: number };

/**
 * Where document bytes live. The database keeps `storageProvider` + `storageKey` per file; the provider
 * turns a key back into bytes. Keys are opaque, generated by the provider, and never contain user input.
 */
export interface StorageProvider {
  readonly name: StorageProviderName;
  /** Streams `body` into storage and resolves once it is complete and durable. */
  put(body: Readable, options: PutOptions): Promise<StoredObject>;
  /** The object's bytes, or a part of them. Throws `StorageNotFoundError` when it is gone. */
  get(key: string, range?: ByteRange): Promise<Readable>;
  /** Idempotent: deleting a missing object is not an error. */
  delete(key: string): Promise<void>;
  /** `null` when the object does not exist. */
  stat(key: string): Promise<{ sizeBytes: number } | null>;
}

export class StorageLimitError extends Error {
  constructor(readonly maxBytes: number) {
    super(`Upload exceeds ${maxBytes} bytes`);
  }
}

export class StorageNotFoundError extends Error {
  constructor(key: string) {
    super(`No stored object for key ${key}`);
  }
}

export class InvalidStorageKeyError extends Error {
  constructor() {
    super("Invalid storage key");
  }
}
