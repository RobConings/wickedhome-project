import assert from "node:assert/strict";
import { after, it } from "node:test";
import { db } from "../lib/db";
import { shoppingSessionFixture } from "./sessions-test-helpers";
import { shoppingSessionCoverage } from "./sessions.service";
const enabled = process.env.SHOPPING_INTEGRATION_TESTS === "1";
after(async () => { if (enabled) await db.$disconnect(); });
it("returns only outstanding active assignments from the current household without recording purchases", { skip: !enabled }, async t => {
 const f = await shoppingSessionFixture(t);
 const visit = await f.start();
 const before = await f.quantity();
 let result = await shoppingSessionCoverage(f.user);
 assert.equal((await shoppingSessionCoverage({ ...f.user, householdId: "another-household" })).sessions.length, 0);
 assert.equal((await shoppingSessionCoverage({ ...f.user, role: "child" })).sessions[0]?.id, visit.id);
 assert.equal(result.sessions[0]?.id, visit.id); assert.ok(result.sessions[0]?.items.some(item => item.requirementIds.includes(f.requirement.id)));
 await db.shoppingSessionItem.update({ where: { id: visit.items[0]!.id }, data: { purchasedQuantity: 1 } });
 assert.equal((await shoppingSessionCoverage(f.user)).sessions[0]?.items[0]?.purchasedQuantity, 1);
 await db.shoppingSessionItem.update({ where: { id: visit.items[0]!.id }, data: { status: "SKIPPED" } });
 assert.equal((await shoppingSessionCoverage(f.user)).sessions[0]?.items.length, 0);
 await db.shoppingSessionItem.update({ where: { id: visit.items[0]!.id }, data: { status: "OPEN", purchasedQuantity: visit.items[0]!.quantity } });
 assert.equal((await shoppingSessionCoverage(f.user)).sessions[0]?.items.length, 0);
 await db.shoppingSessionItem.update({ where: { id: visit.items[0]!.id }, data: { purchasedQuantity: 0, removedAt: new Date() } });
 assert.equal((await shoppingSessionCoverage(f.user)).sessions[0]?.items.length, 0);
 await db.shoppingSession.update({ where: { id: visit.id }, data: { status: "CLOSED" } });
 assert.equal((await shoppingSessionCoverage(f.user)).sessions.length, 0);
 await db.shoppingSession.update({ where: { id: visit.id }, data: { status: "DELETED" } });
 assert.equal((await shoppingSessionCoverage(f.user)).sessions.length, 0);
 result = await shoppingSessionCoverage({ ...f.user, householdId: "another-household" }); assert.deepEqual(result.sessions, []);
 assert.equal(await f.quantity(), before); assert.equal(await db.stockPurchase.count({ where: { householdId: f.home.id } }), 0);
});
