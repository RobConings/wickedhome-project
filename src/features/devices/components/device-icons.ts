import {
  ActivityIcon,
  AlarmSmokeIcon,
  AppWindowIcon,
  BatteryMediumIcon,
  BellIcon,
  BlindsIcon,
  CameraIcon,
  CctvIcon,
  DoorOpenIcon,
  DropletsIcon,
  FanIcon,
  FlameIcon,
  GaugeIcon,
  HeaterIcon,
  LightbulbIcon,
  LockIcon,
  PersonStandingIcon,
  PlugIcon,
  PowerIcon,
  RefrigeratorIcon,
  RouterIcon,
  ShieldIcon,
  SirenIcon,
  SnowflakeIcon,
  SpeakerIcon,
  SunIcon,
  ThermometerIcon,
  TvIcon,
  WashingMachineIcon,
  WavesIcon,
  WindIcon,
  ZapIcon,
  type LucideIcon,
} from "lucide-react";
import type { DeviceIconKey } from "../types/devices";

/** Icon per key in DEVICE_ICONS. The keys are stored; the icons are only a rendering choice. */
export const DEVICE_ICON_COMPONENTS: Record<DeviceIconKey, LucideIcon> = {
  window: AppWindowIcon,
  door: DoorOpenIcon,
  blinds: BlindsIcon,
  thermometer: ThermometerIcon,
  droplets: DropletsIcon,
  snowflake: SnowflakeIcon,
  heater: HeaterIcon,
  fan: FanIcon,
  "washing-machine": WashingMachineIcon,
  refrigerator: RefrigeratorIcon,
  plug: PlugIcon,
  zap: ZapIcon,
  power: PowerIcon,
  shield: ShieldIcon,
  siren: SirenIcon,
  smoke: AlarmSmokeIcon,
  flame: FlameIcon,
  bell: BellIcon,
  lock: LockIcon,
  battery: BatteryMediumIcon,
  lightbulb: LightbulbIcon,
  sun: SunIcon,
  motion: PersonStandingIcon,
  activity: ActivityIcon,
  camera: CameraIcon,
  cctv: CctvIcon,
  waves: WavesIcon,
  wind: WindIcon,
  gauge: GaugeIcon,
  tv: TvIcon,
  router: RouterIcon,
  speaker: SpeakerIcon,
};

/** Unknown keys (e.g. from an older version) fall back to a plug. */
export const deviceIconComponent = (key: string | null | undefined): LucideIcon =>
  (key && DEVICE_ICON_COMPONENTS[key as DeviceIconKey]) || PlugIcon;
