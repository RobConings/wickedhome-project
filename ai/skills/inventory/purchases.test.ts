import assert from "node:assert/strict";
import { it } from "node:test";
import { handleMcpMessage } from "@ai/core/mcp.routes";
import { getEntityResolver, registerEntityResolver, invalidateEntityCache } from "@ai/core/resolve";
import { db } from "@/api/lib/db";
import { actor, setup } from "@/api/inventory/purchases-test-helpers";
import type { StockPurchaseInput } from "@/features/inventory/types/purchases";
import "./tools";
const scan = (reference: string, quantity = 1): StockPurchaseInput => ({ quantity, source: { kind: "scan", reference } });
const receipt = (documentId = "doc-a", shopId = "a", quantity = 1): StockPurchaseInput => ({ quantity, source: { kind: "receipt", reference: "line-1", documentId }, purchasedAt: new Date(Date.now() - 60_000).toISOString(), shopId });
it("MCP requires acquisition provenance, returns purchase ids and blocks a second receipt addition", async (t) => {
  const state = setup(t);
  const { read } = state;
  const user = { ...actor, role: "adult" as const, name: "Rob", email: "test@example.com", householdName: "Home", habitantId: null };
  const original = getEntityResolver("product")!;
  registerEntityResolver({ type: "product", label: "product", skill: "inventory", list: async () => [{ id: "milk", name: "Melk" }] });
  invalidateEntityCache(actor.householdId);
  t.after(() => { registerEntityResolver(original); invalidateEntityCache(actor.householdId); });
  state.stub(db.product, "findFirst", async () => ({ id: "milk", stockProductId: null }));
  state.stub(db.stockItem, "findMany", async () => [read().stock]);
  state.stub(db.shop, "findMany", async () => []);
  state.stub(db.auditEntry, "create", async () => ({}));
  const identity = { user, tokenId: "purchase-test", tokenName: "Test", scope: "write" as const };
  const call = async (name: string, args: Record<string, unknown>) => await handleMcpMessage({ jsonrpc: "2.0", id: 1, method: "tools/call", params: { name, arguments: { ...args, confirm: true } } }, identity, new AbortController().signal) as { result: { isError: boolean; content: { text: string }[]; structuredContent?: { purchase: { added: number; purchaseIds: string[] } } } };
  const legacy = await call("inventory_change_stock", { product: "Melk", action: "add", amount: 1 });
  assert.equal(legacy.result.isError, true); assert.match(legacy.result.content[0]!.text, /stable source/); assert.equal(read().movements.length, 0);
  const added = await call("inventory_record_purchase", { product: "Melk", ...scan("mcp") });
  assert.equal(added.result.isError, false, added.result.content[0]?.text);
  assert.equal(added.result.structuredContent?.purchase.added, 1);
  const duplicate = await call("inventory_record_purchase", { product: "Melk", ...receipt() });
  assert.equal(duplicate.result.isError, true); assert.match(duplicate.result.content[0]!.text, /already added/);
  const linked = await call("inventory_record_purchase", { product: "Melk", ...receipt(), existingPurchaseIds: added.result.structuredContent!.purchase.purchaseIds });
  assert.equal(linked.result.isError, false, linked.result.content[0]?.text); assert.equal(linked.result.structuredContent?.purchase.added, 0);
  assert.equal(read().stock.quantity.toNumber(), 3);
});
