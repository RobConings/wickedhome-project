if (process.argv.includes("--write")) fs.writeFileSync("docs/COMPONENT-COMPOSITION-AUDIT.md", report);
console.log(`${rows.length} UI files across ${groups.size} layers/features; ${screenCount} screens; ${violations.length} screen composition violations; ${componentDrift.length} feature files with static layout drift; ${missing.length} files without mirrored stories.`);
if (process.argv.includes("--check") && (violations.length || componentDrift.length || paragraphDrift.length)) {
  for (const row of violations) console.error(`${row.file}: use shared layout/Text or a domain component`);
  for (const row of componentDrift) console.error(`${row.file}:${row.adHoc.join(",")}: use layout primitives`);
  for (const row of paragraphDrift) console.error(`${row.file}: use Text or a shared text composition`);
  process.exitCode = 1;
}
